package module01_basics;

public class Basics18 {
    static void main(String[] args) {

        //System.out.println();

        // System.out.println() is used to print output on the console.
        // After printing the output, the cursor automatically moves to the next line.
        System.out.println("Hello World");

        // Core Definitions
        // System is a predefined (built-in) Java class.
        // It provides useful utility fields and methods that interact
        // with the Java runtime environment.
        //
        // out is a static object of the PrintStream class.
        // println() is a method of the PrintStream class.

        // PRINTING DIFFERENT DATA TYPES

        // println() can print different types of data:
        System.out.println(3);          // int value
        System.out.println(3.0);        // double value
        System.out.println(3.7364667);  // double value
        System.out.println(677);        // int value
        System.out.println("Hello");    // String value
        System.out.println('A');        // char value
        System.out.println(true);       // boolean value

        // An empty println() prints a blank line.
        System.out.println();

        // Summary: We can use println() to print:
        // - Numbers
        // - Text (Strings)
        // - Characters
        // - Boolean values
        // - Objects and many other data types



    }
}
