package module02_string;

public class String14 {
    static void main(String[] args) {
        // Rule: String.valueOf() converts a primitive int into a real String object.
        int a = 10;
        String s = String.valueOf(a);
        System.out.println(s); // Output: "10"

        // now 10 is a string we can use all string method with s.
    }
}
