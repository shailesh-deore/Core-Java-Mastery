package module04_loops;

public class Loops16 {
    static void main(String[] args) {

        System.out.println("Rocket preparing for takeoff...");

        // This loop starts at 5 and counts down to 1
        for (int i = 5; i >= 1; i--) {
            System.out.println("T-minus " + i + " seconds...");
        }

        // This runs after the loop finishes
        System.out.println("🚀 BLAST OFF! The rocket has launched!");
    }
}




